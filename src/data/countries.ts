export function countriesInScope(
  scope: ScopeId,
  weakIds: string[] = [],
): Country[] {
  switch (scope) {
    case "all":
      return COUNTRIES.filter((c) => c.region !== "caucasus");
    case "benelux":
      return COUNTRIES.filter((c) => ["NL", "BE", "LU"].includes(c.id));
    case "west":
    case "north":
    case "south":
    case "east":
    case "caucasus":
      return COUNTRIES.filter((c) => c.region === scope);
    case "eu":
      return COUNTRIES.filter((c) => c.eu);
    case "micro":
      return COUNTRIES.filter((c) => c.micro);
    case "weak":
      if (weakIds.length === 0) {
        return COUNTRIES.filter((c) => c.region !== "caucasus");
      }
      return COUNTRIES.filter((c) => weakIds.includes(c.id));
    default:
      return COUNTRIES.filter((c) => c.region !== "caucasus");
  }
}

export function countryLabel(country: Country): string {
  return country.article ? `${country.article} ${country.name}` : country.name;
}

